"""Solve the reference networks with the Python GRM (grm-core) and write tests/golden.hpp, the numbers the
C++ port must reproduce.  Usage: python tools/make_golden.py /path/to/grm-core"""
import math

import numpy as np
import os
import sys
from unittest import mock

GRM_CORE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "..", "grm-core")
sys.path.insert(0, os.path.abspath(GRM_CORE))
for name in ("tkinter", "tkinter.filedialog", "tkinter.messagebox", "tkinter.ttk", "sounddevice"):
    sys.modules.setdefault(name, mock.MagicMock())

import grm_guitar as g  # noqa: E402
from grm import GlobalRelationalNetwork  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "tests", "golden.hpp")
lines = ["// generated by tools/make_golden.py from grm-core (Python): do not edit", "#pragma once", "",
         "struct GoldenValue { const char* test; const char* node; double value; double sigma_dex; };", "",
         "static const GoldenValue GOLDEN[] = {"]


def emit(test, out, nodes):
    for n in nodes:
        lines.append(f'    {{"{test}", "{n}", {out["values"][n]!r}, {out["sigma_dex"][n]!r}}},')


# the six strings, open and at the 5th fret
for i, s in enumerate(g.STRINGS):
    core = 0.45 if s["wound"] else 1.0
    for fret in (0, 5):
        out = g.play_string_model(s["L"], s["mu"], s["T"], fret, core)
        emit(f"string{i}_fret{fret}", out, ["f1", "c", "B", "Zs", "Leff", "d"])
    out = g.tune_string_model(s["L"], s["mu"], s["target"], core)
    emit(f"tune{i}", out, ["T", "c", "B"])

# the attack, pick and finger, on the low E and the high E
for i in (0, 5):
    s = g.STRINGS[i]
    for tech in ("pick", "finger"):
        out = g.pluck_network(s["mu"], s["L"], s["T"], 3, 0.18, 2.0, tech, 0.71)
        emit(f"pluck{i}_{tech}", out, ["ks", "y0", "tau", "fc", "Ec", "xr"])

# a signed-node fn network: a point on the unit circle (x measured, y found), plus a sum relation
net = GlobalRelationalNetwork(
    {"x": {"guess": 0.5, "scale": "lin"}, "y": {"guess": 0.5, "scale": "lin"}, "r": {"guess": 2.0}},
    [{"name": "circle", "type": "fn", "nodes": ["x", "y", "r"], "f": lambda v: v["x"] ** 2 + v["y"] ** 2 - v["r"] ** 2,
      "sigma": 1e-9},
     {"name": "sum", "type": "sum", "terms": {"x": 1, "y": 1}, "K": 1.3, "sigma": 1e-3}])
out = net.solve(measured_dict={"r": (1.0, 1e-6)})
emit("circle", out, ["x", "y", "r"])

def raw(test, node, value):
    lines.append(f'    {{"{test}", "{node}", {float(value)!r}, 0.0}},')


# body and bridge
out = g.body_network()
emit("body", out, ["f_lo", "f_hi", "f3", "f7", "Mm", "Zp", "mb", "fT", "frad", "fb", "fH"])
modes, bv = g.body_modes()
for f in (82.0, 196.0, 1000.0, 3000.0):
    Y = g.bridge_admittance([f], modes, bv)[0]
    raw("admittance", f"re{int(f)}", Y.real)
    raw("admittance", f"im{int(f)}", Y.imag)

# room
for name, mat in (("Living room", "Plaster"), ("Church", "Painted brick")):
    v = g.room_network(g.ROOMS[name], mat)
    for n in ["V", "S", "rc", "fs"] + [f"RT{b}" for b in range(6)]:
        raw("room_" + name.split()[0], n, v[n])

# palm: low E open, high E at the 3rd fret
for i, fret in ((0, 0), (5, 3)):
    s = g.STRINGS[i]
    out = g.palm_network(s["mu"], s["L"], fret, T=s["T"])
    v = out["values"]
    raw(f"palm{i}", "f1", v["f1"])
    for n in (0, 1, 4, 9):
        if n < len(v["ratio"]):
            raw(f"palm{i}", f"ratio{n}", v["ratio"][n])
            raw(f"palm{i}", f"sigma{n}", v["sigma"][n])
    raw(f"palm{i}", "count", len(v["ratio"]))

# finger on a wound string: a slide 3 -> 7 and a lift
s = g.STRINGS[1]
emit("squeak_slide", g.squeak_network(s["mu"], s["L"], 0.45, 3, 7, 0.12, 0.8), ["fsq", "P", "fL", "v", "p", "cL"])
emit("squeak_lift", g.squeak_network(s["mu"], s["L"], 0.45, 5, 0, 0.05, 0.8), ["fsq", "P", "fL", "v"])
emit("action7", g.action_network(0.648, 7), ["xf", "h"])


class Exact:
    def normal(self, mean=0.0, sd=1.0):
        return mean


strokes = [(0.0, 0), (0.25, 1), (0.5, 2), (1.0, 4), (1.25, 5)]
for k, st in enumerate(g.player_network(strokes, 0.25, 0.2, Exact())):
    for n in ("t", "A", "v", "p", "d", "palm_x", "palm_N"):
        raw("player", f"{n}{k}", st[n])
    if k == 1:
        for (i, delay, share) in g.strum_contacts([0, 1, 2, 3, 4, 5], st, False):
            raw("contacts_down", f"delay{i}", delay)
            raw("contacts_down", f"share{i}", share)
        for (i, delay, share) in g.strum_contacts([5, 4, 3, 2, 1, 0], st, True):
            raw("contacts_up", f"delay{i}", delay)
            raw("contacts_up", f"share{i}", share)

# one string as it sounds (synthesize_string), with and without the palm: RMS of windows of the force
s = g.STRINGS[1]
v = g.play_string_model(s["L"], s["mu"], s["T"], 3, 0.45)["values"]
a = g.pluck_network(s["mu"], s["L"], s["T"], 3, 0.22, 2.0, "pick", 0.71)["values"]
modes, bv = g.body_modes()
loss = g.bridge_loss(modes, bv, v["c"], v["Leff"], v["Zs"])
palm = g.palm_network(s["mu"], s["L"], 3, T=s["T"])["values"]
for name, pv in (("voice", None), ("voice_palm", palm)):
    y = g.synthesize_string(v["f1"], v["B"], 1.0, 0.22, 3.0, 0.6, release_tau=a["tau"], extra_sigma=loss, palm=pv,
                            Zs=v["Zs"], palm_attack=True) * s["T"] * math.pi / v["Leff"] * a["y0"]
    for k, (t0, t1) in enumerate(((0, 441), (441, 4410), (4410, 44100))):
        raw(name, f"rms{k}", float(np.sqrt(np.mean(y[t0:t1] ** 2))))
    raw(name, "sample100", float(y[100]))

lines += ["};", ""]
with open(OUT, "w") as f:
    f.write("\n".join(lines))
print("written", OUT, len([l for l in lines if l.startswith("    {")]), "values")
